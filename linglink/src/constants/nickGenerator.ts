function pick(list: readonly string[]): string {
  return list[Math.floor(Math.random() * list.length)]!
}

/** First sign-in name: given name, a connector, and a surname. */
export function generateNickname(): string {
  const style = Math.floor(Math.random() * 3)
  const connector =
    style === 0 ? pick(realConnectors) : style === 1 ? pick(fantasyConnectors) : pick(connectors)
  return `${pick(firstNames)} ${connector} ${pick(lastNames)}`
}
